"""Generate the viewer's static routing catalogue; never modify the source CSV."""

import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
import re


def build_catalogue(source: bytes) -> str:
    text = source.decode("utf-8-sig")
    if "\x00" in text or "\ufffd" in text:
        raise ValueError("Invalid UTF-8 catalogue export")
    rows = [row for row in csv.reader(io.StringIO(text, newline=""), strict=True)
            if any(value.strip() for value in row)]
    header = [value.strip() for value in rows[0]] if rows else []
    fields = ["catalogNumber", "Family", "Scientific Name"]
    if any(header.count(field) != 1 for field in fields):
        raise ValueError("The catalogue needs one column each named " + ", ".join(fields))
    columns = [header.index(field) for field in fields]
    locations, location_ids, records = [], {}, []
    for row in rows[1:]:
        if len(row) > len(header):
            raise ValueError("The catalogue CSV has a row with extra columns")
        number, family, species = [row[index] if index < len(row) else "" for index in columns]
        match = re.fullmatch(r"E?([0-9]+)", number.strip(), flags=re.IGNORECASE)
        if not match:
            continue  # Same numbered-entry scope as the viewer's CSV reader.
        location = (family, species)
        if location not in location_ids:
            location_ids[location] = len(locations)
            locations.append(location)
        records.append([match[1], location_ids[location]])
    if not records:
        raise ValueError("The catalogue contains no numbered entries")
    encode = lambda value: json.dumps(value, ensure_ascii=True, separators=(",", ":"))
    # Hash only published routing data, not unused collection fields or availability flags.
    digest = hashlib.sha256(encode([locations, records]).encode("ascii")).hexdigest()
    return (
        "// Generated by build_catalogue.py. Routing only; reports and scans remain live on Drive.\n"
        "// Regenerate from the source CSV if a number, family or scientific name changes.\n"
        "const VIEWER_CATALOGUE = {\n"
        '"format":1,\n'
        f'"sha256":"{digest}",\n'
        '"locations":[\n' + ",\n".join(encode(location) for location in locations) + "\n],\n"
        '"records":[\n' + ",\n".join(
            ",".join(encode(record) for record in records[start:start + 40])
            for start in range(0, len(records), 40)
        ) + "\n]\n};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", type=Path, help="Read-only source UTF-8 CSV")
    parser.add_argument("--output", type=Path, default=Path(__file__).with_name("Catalogue.gs"))
    args = parser.parse_args()
    if args.csv.resolve() == args.output.resolve():
        parser.error("Output must differ from the source CSV")
    source = args.csv.read_bytes()
    result = build_catalogue(source)
    args.output.write_text(result, encoding="utf-8", newline="\n")
    print(f"Wrote {args.output}: {len(result.encode('utf-8')):,} bytes (source {len(source):,} bytes)")


if __name__ == "__main__":
    main()
